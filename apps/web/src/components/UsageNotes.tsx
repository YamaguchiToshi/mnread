/**
 * 利用上の注意と既知の限界（PLAN Phase 6）
 *
 * このアプリは Pages で公開されており、臨床検証（Phase 5）が終わる前から
 * 医療者の手元で動く。PLAN「公開時の注意」が求めるのは、画面と全出力に
 * **版と検証状況を明示する**ことである。出力側（電子カルテ文・A4レポート・
 * 書き出し）には既に入っているが、画面には解析結果の脇に版があるだけで、
 * 「何がどこまで確かめられていないか」はどこにも書いていなかった。
 *
 * 表示の設計:
 *   - 帯は常設で、閉じられない。検証状況は読み飛ばしてよい情報ではない。
 *   - 詳細は既定で畳む。検査中に画面を占有させない。
 *   - 端末に何も保存しない設計のため「読んだので今後は出さない」は作れない
 *     （再読み込みのたびに開くことになる）。常設の帯＋任意展開が唯一成立する形。
 *   - `no-print`。A4 レポートには患者向けの注意書きが別にあり（SPEC §8.2.2）、
 *     開発者向けの限界一覧を患者に渡す紙へ載せる意味はない。
 *
 * 文面はすべて SPEC.md の記述に対応する。数値の算出はここでは一切行わない
 * （ADR-0010）。版は core の定数をそのまま出す。
 */

import { ALGORITHM_VERSION, SPEC_VERSION } from "@mnread/core";
import { useState, type JSX } from "react";

export function UsageNotes(): JSX.Element {
  const [open, setOpen] = useState(false);

  return (
    <div className="usage-notes no-print">
      <p className="usage-banner" data-testid="usage-banner">
        <span>
          <strong>実測記録による検証は未完了です。</strong>
          値は院内の参考値であり、診断・治療の判断には用いません。
          <span className="usage-versions" data-testid="usage-versions">
            （仕様版 {SPEC_VERSION} / アルゴリズム版 {ALGORITHM_VERSION}）
          </span>
        </span>
        <button
          type="button"
          className="usage-toggle"
          data-testid="usage-notes-toggle"
          aria-expanded={open}
          aria-controls="usage-notes-detail"
          onClick={() => setOpen((o) => !o)}
        >
          {open ? "閉じる" : "利用上の注意と既知の限界"}
        </button>
      </p>

      {open && (
        <section
          id="usage-notes-detail"
          className="usage-detail"
          data-testid="usage-notes-detail"
          aria-label="利用上の注意と既知の限界"
        >
          <h2>検証の状況</h2>
          <ul>
            <li>
              計算式は一次資料（公式マニュアルと Q&amp;A）の数表に対して照合済みです。
              ポイント換算・距離補正・小数視力・読書速度、およびマニュアル §4 の測定例
              19行は、いずれも原典の記載値を再現します。
            </li>
            <li>
              <strong>
                実測記録との突き合わせ、目視による臨界文字サイズとの一致確認、
                患者・支援者向け文言の監修は未実施です。
              </strong>
            </li>
            <li>
              自動推定が目視確認を求める閾値は、合成曲線で決めた暫定値です。
              警告が過剰に出る側へ倒してあります（臨床の主値が検者の目視判定である以上、
              見落とすより出しすぎるほうが安全なためです）。
            </li>
          </ul>

          <h2>このツールの位置づけ</h2>
          <ul>
            <li>
              測定値の計算と表示のみを行い、診断・治療の判断は行いません。
              推奨倍率・推奨文字サイズは参考値です。
            </li>
            <li>
              臨界文字サイズと最大読書速度の主値は、<strong>検者の目視判定</strong>です。
              自動推定値は併記であって、置き換えではありません。
            </li>
            <li>
              臨界文字サイズの値は、必ず算出法とともにお読みください。
              算出法を伴わない数値は結果として扱えません。
            </li>
          </ul>

          <h2>データの取り扱い</h2>
          <ul>
            <li>
              入力した値は端末にもサーバにも保存されません。再読み込みすると消えます。
              外部への通信は行いません。
            </li>
            <li>
              氏名欄は設けていません。書き出したファイルの取り扱いは院内規程に従ってください。
            </li>
          </ul>

          <h2>既知の限界</h2>
          <dl className="usage-limits">
            <dt>ポイント値は書体によって実寸が変わります</dt>
            <dd>
              表示するポイント値は MNREAD-J の文字設計（明朝体）に対応した相当値です。
              同じポイント数でも書体により字面の大きさは異なるため、
              支援先で実際に使う書体そのもので確認してください。
            </dd>

            <dt>MNREAD-Jk の値は、漢字かな交じり文の値ではありません</dt>
            <dd>
              Jk はひらがな単語で測ります。漢字かな交じりの教材に当てる場合は、
              臨界文字サイズに 0.1 logMAR を加えた値を参考として併記するにとどまり、
              MNREAD-J で測り直した値の代わりにはなりません。
            </dd>

            <dt>読書アクセシビリティ指標に日本語版の基準値がありません</dt>
            <dd>
              英語版 ACC の正規化定数は英語母語話者から得られたもので、
              日本語の cpm には転用できません。本アプリは正規化しない平均速度だけを出します。
              英語版 ACC や、正規化値を用いた他施設の値とは直接比較できません。
            </dd>

            <dt>判読3ゾーンの区分は、本ツールの裁定です</dt>
            <dd>
              「読めない / 読めるが遅くなる / 最も速く読める」の境界を読書視力と
              臨界文字サイズに置くことには、原典の規定がありません。
              患者・支援者向けの目安に限って用い、電子カルテ用テキストと生データには
              持ち込んでいません。
            </dd>

            <dt>最大読書速度は3方式を併記します</dt>
            <dd>
              原典は本文と測定例で算出法が食い違っており（測定例では 412 / 411 / 411 cpm に
              分かれ、原典自身の記載値は 411）、どれか1つに寄せると、
              原典が決めていないことをこのツールが黙って決めることになります。
            </dd>

            <dt>指数減衰フィットが当てはまらない曲線があります</dt>
            <dd>
              折れ線状に鋭く曲がる曲線に指数モデルは原理的に適合しません。
              残差が大きい場合は「推定不能」と表示し、値を出しません。
            </dd>

            <dt>読書視力の表示桁より細かい差は画面に出ません</dt>
            <dd>
              誤り1文字あたりの読書視力の変化は表示桁（小数第2位）より細かいため、
              誤り数が1文字違っても表示上は同じ値になることがあります。
              生データの書き出しは丸めていません。
            </dd>

            <dt>大きい文字が読めない例の扱いは、原典の想定外です</dt>
            <dd>
              視野障害などで大きい文字側が読めない場合の読書視力の数え方は、
              原典に規定がありません。読み損じとして算入したうえで、
              目視確認を求めるフラグを立てています。
            </dd>
          </dl>

          <p className="usage-source">
            根拠と未解決事項は、開発リポジトリの SPEC.md（§5.6・§5.7・§5.8、
            および未解決事項 OPEN-2 / 4 / 6 / 7）に記載しています。
          </p>
        </section>
      )}
    </div>
  );
}
